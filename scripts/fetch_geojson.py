def _classify_park(p):
    if p.get('type') == 'greenway':
        return 'greenway'
    if p['name'] in METROPOLITAN_PARKS:
        return 'large_general'   # 都営公園特例
    if p['area'] >= 500000:
        return 'large_wide'
    if p['area'] >= 150000:
        return 'large_general'
    if p['area'] >= 50000:
        return 'medium'
    if p['area'] >= 10000:
        return 'small'
    return 'tiny'

MIN_WALK = 35

def _distance_factor(dist):
    if dist <= 500:   return 1.0
    elif dist <= 1000: return 0.85
    elif dist <= 1500: return 0.65
    elif dist <= 2000: return 0.45
    else:              return 0.0

def _park_base_score(p):
    cls = _classify_park(p)
    if cls == 'large_wide':    return 60
    elif cls == 'large_general': return 55
    elif cls == 'medium':        return 20
    elif cls == 'small':         return 4
    else:                        return 0

def calc_osm_score(nearby_parks, st_lat, st_lng):
    """公園・緑地・ドッグラン・河川からosm_score（距離係数適用）を計算"""
    # 公園スコア（緑地除く・距離係数適用）
    park_score = 0
    for p in nearby_parks:
        if p.get('type') == 'greenway':
            continue
        dist = min_dist_to_park(p['name'], p['lat'], p['lng'], st_lat, st_lng)
        park_score += _park_base_score(p) * _distance_factor(dist)
    park_score = min(round(park_score), 90)

    # 緑地スコア（距離係数適用）
    greenway_score = 0
    for p in nearby_parks:
        if p.get('type') != 'greenway':
            continue
        dist = min_dist_to_park(p['name'], p['lat'], p['lng'], st_lat, st_lng)
        if p['area'] >= 100000:  gw_base = 20
        elif p['area'] >= 10000: gw_base = 8
        else: continue
        greenway_score += gw_base * _distance_factor(dist)
    greenway_score = min(round(greenway_score), 30)

    # ドッグランボーナス（距離係数適用）
    dogrun_parks = [p for p in nearby_parks if p['dogrun'] and p.get('type') != 'greenway']
    if dogrun_parks:
        max_dogrun = max(dogrun_parks, key=lambda p: p['area'])
        dist = min_dist_to_park(max_dogrun['name'], max_dogrun['lat'], max_dogrun['lng'], st_lat, st_lng)
        factor = _distance_factor(dist)
        cls = _classify_park(max_dogrun)
        if cls == 'large_wide':      dr_base = 20
        elif cls == 'large_general': dr_base = 18
        elif cls == 'medium':        dr_base = 22
        else:                        dr_base = 0
        dogrun_bonus = round(dr_base * factor)
    else:
        dogrun_bonus = 0

    # 河川ボーナス（500m以内+10pt）
    river_bonus = get_river_bonus(st_lat, st_lng)

    return min(park_score + greenway_score + dogrun_bonus + river_bonus, 90)


def get_walk_base(st, osm_cache, stations, ward_default):
    """2km圏内の居住駅のosm_score平均をbaseとする。該当なければ区デフォルト"""
    nearby_osms = []
    for other in stations:
        if other['id'] == st['id']:
            continue
        if other['name'] in NON_RESIDENTIAL_STATIONS:
            continue
        dist = haversine(st['lat'], st['lng'], other['lat'], other['lng'])
        if dist <= 2000:
            other_osm = osm_cache.get(other['id'], 0)
            if other_osm > 0:
                nearby_osms.append(other_osm)
    if nearby_osms:
        return round(sum(nearby_osms) / len(nearby_osms))
    return ward_default.get(st.get('ku', ''), 40)


def apply_walk_score(osm, base, base_is_override=False, walk_max=None):
    """osm_scoreとbaseからwalkスコアを確定"""
    if osm == 0:
        walk = base
    elif osm < base * 0.5:
        walk = round(osm * 0.4 + base * 0.6)
    else:
        walk = osm   # 公園データ十分 → osm直接使用
    if base_is_override:
        walk = max(walk, base)
    if walk_max is not None:
        walk = min(walk, walk_max)
    walk = max(walk, MIN_WALK)
    if walk_max is not None:
        walk = min(walk, walk_max)
    return walk

def calc_medical_score(nearby_vets, nearby_cafes, nearby_grooming, base):
    cafe_score  = min(len(nearby_cafes)   * 5,  55)
    vet_score   = min(len(nearby_vets)    * 10, 30)
    groom_score = min(len(nearby_grooming)* 5,  15)
    emerg = any(
        any(kw in v.get('name', '') for kw in ['夜間', '救急', '24'])
        for v in nearby_vets
    )
    emerg_score = 20 if emerg else 0
    raw       = cafe_score + vet_score + emerg_score + groom_score  # max 120
    osm_score = max(30, min(90, round(30 + (raw / 120) * 60)))
    if len(nearby_cafes) == 0 and len(nearby_vets) == 0:
        return base
    return max(30, min(90, round(osm_score * 0.7 + base * 0.3)))

def calc_mobility_score(fac, sid, st_lat, st_lng, ku):
    pet_ok = sum(1 for _, la, lo, ok in CARSHARE_STATIONS
                 if ok and haversine(st_lat, st_lng, la, lo) <= RADIUS)
    pet_cs_score = min(pet_ok * 10, 20)
    gen_cs_score = min(len(fac['carshares']) * 4, 20)
    rental_score = min(len(fac['car_rentals']) * 7, 14)
    park_contrib = PARKING_WARD.get(ku, 55) * 0.3
    raw          = pet_cs_score + gen_cs_score + rental_score + park_contrib
    normalized   = round(30 + (raw / 73) * 50)
    return max(30, min(80, normalized))

