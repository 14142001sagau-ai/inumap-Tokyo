def make_id(ku, name):
    if ku in EXISTING_IDS and name in EXISTING_IDS[ku]:
        return EXISTING_IDS[ku][name]
    key = ku + name
    h = hashlib.md5(key.encode()).hexdigest()[:6]
    clean = unicodedata.normalize('NFKC', name)
    clean = re.sub(r'[^\w]', '', clean)
    return clean + '_' + h

